// Shared companion test vectors: every Wiqo companion (Mac/Swift, Windows/C#) must produce and
// verify exactly these values. RFC 8785 defines canonical numbers and strings by ECMAScript's own
// rules, so JavaScript is the reference implementation here.
// Usage: node contracts/companion/generate-vectors.mjs [--check]
import { createHash, createHmac } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const output = new URL("./vectors.json", import.meta.url);

function canonical(value) {
  if (value === null || typeof value !== "object") return JSON.stringify(value);
  if (Array.isArray(value)) return `[${value.map(canonical).join(",")}]`;
  // RFC 8785: keys sorted by UTF-16 code units, which is JavaScript's default string order.
  return `{${Object.keys(value).sort().map((key) => `${JSON.stringify(key)}:${canonical(value[key])}`).join(",")}}`;
}

const hmac = (key, message) => createHmac("sha256", key).update(message, "utf8").digest("hex");
const sha256 = (text) => createHash("sha256").update(text, "utf8").digest("hex");

const canonicalInputs = [
  '{"b":2,"a":1}',
  '{"numbers":[1.0,-0,0.1,1e21,1e-7,123456789012345680000,0.000001,-12.5,5e-324]}',
  '{"text":"çğıöşü ÇĞİÖŞÜ","slash":"a/b","quote":"\\"x\\"","control":"\\u0001\\n\\t"}',
  '{"emoji":"👋","separator":"\\u2028"}',
  '{"€":1,"a":2,"A":3,"é":4,"\\ud83d\\ude00":5}',
  '{"nested":{"z":[true,false,null],"y":{"b":"",  "a":[]}}}',
  '{"path":"~/Desktop/deneme","windows":"C:\\\\Users\\\\Ada"}'
];

const token = "wiqo-test-pairing-token-0123456789abcdef";
const grants = [
  { grantId: "3F2504E0-4F89-41D3-9A0C-0305E82C3301", rootDirectory: "~/Desktop/deneme", mode: "full", expiresAt: 1790000000 },
  { grantId: "7c9e6679-7425-40de-944b-e07fc1f90ae7", rootDirectory: "C:\\Users\\Ada\\proje", mode: "read", expiresAt: 1790003600 },
  { grantId: "0b8e7d2a-1111-4c3b-8d9e-aaaaaaaaaaaa", rootDirectory: "/Users/ada/çalışma alanı", mode: "full", expiresAt: 1790028800 }
].map((grant) => ({
  ...grant,
  token,
  signature: hmac(token, `wiqo-terminal-grant:v1:${grant.grantId.toLowerCase()}:${grant.rootDirectory}:${grant.mode}:${grant.expiresAt}`)
}));

const commands = [
  { id: "B5F1B7E4-8A55-4C4D-9F6B-1D2C3E4F5A6B", type: "openURL", epochMs: 1790000000123, nonce: "n-1", payload: { kind: "url", value: "https://wiqo.app/a?b=1" } },
  { id: "c0ffee00-0000-4000-8000-000000000001", type: "searchFiles", epochMs: 1790000000456, nonce: "nonce/ğ", payload: { kind: "fileSearch", value: { query: "notlar ğ/ü 😀" } } }
].map((command) => {
  const payloadCanonical = canonical(command.payload);
  const digest = sha256(payloadCanonical);
  return {
    ...command,
    token,
    payloadCanonical,
    signature: hmac(token, `wiqo-command:v2:${command.id.toLowerCase()}:${command.type}:${command.epochMs}:${command.nonce}:${digest}`)
  };
});

const vectors = {
  note: "Generated by generate-vectors.mjs - do not edit by hand.",
  canonicalJson: canonicalInputs.map((input) => ({ input, canonical: canonical(JSON.parse(input)) })),
  terminalGrants: grants,
  commandSignatures: commands
};
const text = `${JSON.stringify(vectors, null, 2)}\n`;

if (process.argv.includes("--check")) {
  // Windows checkouts may normalize tracked text files to CRLF. The vector contract is JSON
  // content; line-ending conversion must not make a current generated file appear stale.
  const current = readFileSync(output, "utf8").replace(/\r\n?/g, "\n");
  if (current !== text) {
    console.error("✖ vectors.json güncel değil: node contracts/companion/generate-vectors.mjs");
    process.exit(1);
  }
  console.log("✔ vectors.json güncel");
} else {
  writeFileSync(output, text);
  console.log(`vectors.json yazıldı (${vectors.canonicalJson.length} JSON, ${grants.length} grant, ${commands.length} komut)`);
}
